import React, { useState } from 'react';
import { createRoot } from 'react-dom/client';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { applyOnlineCommand, createOnlineRoom, joinOnlineRoom, onlineRoomView, type OnlineCommand, type OnlineRoom, type Seat } from '@workspace/squabblemon-engine/multiplayer';
import { DISTRICT_CATALOG, getLegalCardCost, validateDistrictSnapshot, type Lane } from '@workspace/squabblemon-engine/gameEngine';
import { MultiplayerBattle } from '../src/components/MultiplayerBattle';
import '../src/index.css';
import '../src/styles/multiplayer.css';

const params = new URLSearchParams(location.search);
const mode = params.get('mode') ?? 'active';
const hero = params.get('hero') ?? (mode === 'loss' ? 'chonk-lee' : 'franklin-duke');
const code = 'ABCDEF123456';
const gang = ['waterboy', 'edgar', 'transplant', 'youngbull', 'bushedo-brown', 'franklin-duke', 'chonk-lee', 'hooper', 'wifey', 'plug'];
const member = (userId: string, name: string, leader: string) => ({ userId, name, ready: false,
  deck: { id: `review-${userId}`, name: 'Authored review gang', hero: leader, cards: [...gang] } });

/** Isolated review only: each view is generated by legal shared-engine commands. */
function authoredRoom(): OnlineRoom {
  const now = Date.now();
  let room = joinOnlineRoom(createOnlineRoom(member('review-one', 'Review Fighter', hero), 'player', now),
    member('review-two', 'Assigned Rival', hero === 'chonk-lee' ? 'franklin-duke' : 'chonk-lee'), now);
  room.kumite = { tournamentId: 'browser-review-week', matchId: params.get('final') === 'false' ? 'r1-m1' : 'r3-m1', roundDeadline: now + 6 * 3600000 };
  room = applyOnlineCommand(applyOnlineCommand(room, 'player', { type: 'ready' }, now), 'cpu', { type: 'ready' }, now);
  room.match = { ...room.match!, districtSnapshot: validateDistrictSnapshot({ version: 1,
    locations: ['bodega', 'vip-section', 'underground-ring'].map(id => DISTRICT_CATALOG.find(location => location.id === id)!) }) };
  const strong: Seat = mode === 'loss' ? 'cpu' : 'player';
  const turns = mode === 'active' ? 4 : 12;
  for (let index = 0; index < turns && room.status === 'active'; index++) {
    const seat = room.activeSeat;
    const lane = ((room.match!.round - 1) % 3) as Lane;
    if (mode === 'active' || (mode !== 'draw' && seat === strong)) {
      const hand = seat === 'player' ? room.match!.playerHand : room.match!.cpuHand;
      const motion = seat === 'player' ? room.match!.playerMotion : room.match!.cpuMotion;
      const card = hand.find(card => getLegalCardCost(room.match!, seat, card, lane) <= motion);
      if (card) room = applyOnlineCommand(room, seat, { type: 'play', instanceId: card.instanceId, lane, squabble: false }, now);
    }
    room = applyOnlineCommand(room, seat, { type: 'end-turn' }, now);
  }
  if (mode === 'active') {
    const fighter = room.match!.playerHand.find(card => card.cardId === 'youngbull')!;
    room = applyOnlineCommand(room, 'player', { type: 'play', instanceId: fighter.instanceId, lane: 2, squabble: false }, now);
  }
  return room;
}
const evidence = { fixture: true, mode, commands: [] as OnlineCommand[], leaves: 0,
  view: () => onlineRoomView(authoredRoom(), code, 'review-one', Date.now()) };
Object.assign(window, { kumiteBattleReview: evidence });

function Review() {
  const [room, setRoom] = useState(authoredRoom);
  evidence.view = () => onlineRoomView(room, code, 'review-one', Date.now());
  const send = async (command: OnlineCommand) => {
    evidence.commands.push(command);
    // Explicit fixture stub: production still uses the authenticated server API.
    setRoom(current => applyOnlineCommand(current, 'player', command, Date.now()));
    return true;
  };
  return <MultiplayerBattle room={onlineRoomView(room, code, 'review-one', Date.now())} connected busy={false}
    reducedMotion={params.get('profileReduced') === 'true'} send={send} onLeave={() => { evidence.leaves++; document.body.dataset.reviewExit = 'kumite'; }} />;
}
const client = new QueryClient({ defaultOptions: { queries: { retry: false } } });
createRoot(document.getElementById('root')!).render(<QueryClientProvider client={client}><Review /></QueryClientProvider>);
