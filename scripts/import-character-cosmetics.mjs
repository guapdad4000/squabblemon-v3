// Run from the repo root: pnpm --filter @workspace/squabblemon exec node ../../scripts/import-character-cosmetics.mjs /path/to/packs
// The supplied ZIPs remain the original masters; only optimized WebP copies enter public assets.
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const sharp = createRequire(new URL('../artifacts/squabblemon/package.json', import.meta.url))('sharp');
const input = process.argv[2];
if (!input) throw new Error('Pass the directory containing all ten Squabblemon ZIP packs.');
const scratch = await mkdtemp(path.join(tmpdir(), 'squabblemon-cosmetics-'));
const packNames = [1, 2, 3].flatMap(part => ['A', 'B', 'C'].map(batch => `Squabblemon-Stickers-Covers-${part}${batch}.zip`));
packNames.push('Squabblemon-V3-Banners.zip');

try {
  // Read image entries only. Archive README files are metadata, not import instructions.
  const extraction = spawnSync('python3', ['-c', `
import hashlib,json,pathlib,sys,zipfile
source=pathlib.Path(sys.argv[1]); dest=pathlib.Path(sys.argv[2]); images=[]
for pack in json.loads(sys.argv[3]):
 with zipfile.ZipFile(source/pack) as archive:
  for entry in archive.infolist():
   if entry.is_dir() or not entry.filename.endswith('.png'): continue
   parts=pathlib.PurePosixPath(entry.filename).parts
   if len(parts) not in (2,3) or any(p in ('.','..','/') for p in parts): raise ValueError(entry.filename)
   data=archive.read(entry); target=dest/(str(len(images))+'.png'); target.write_bytes(data)
   images.append(dict(pack=pack,member=entry.filename,source=str(target),sha256=hashlib.sha256(data).hexdigest(),bytes=len(data)))
print(json.dumps(images))
`, path.resolve(input), scratch, JSON.stringify(packNames)], { encoding: 'utf8', maxBuffer: 1024 * 1024 });
  if (extraction.status !== 0) throw new Error(extraction.stderr);
  const entries = JSON.parse(extraction.stdout);
  const artwork = {};
  const provenance = [];
  const destinations = new Set();
  const jobs = entries.map(entry => {
    const parts = entry.member.split('/');
    const banner = parts.length === 2;
    const cardId = banner ? parts[1].replace(/-banner\.png$/, '') : parts[1];
    const kind = banner ? 'banner' : parts[2].replace(/\.png$/, '');
    if (!/^[a-z0-9-]+$/.test(cardId) || !/^(banner|deck-cover|sticker-(portrait|action|reaction|emblem|finnam|falcon))$/.test(kind)) throw new Error(entry.member);
    const asset = `assets/cosmetics/${cardId}/${kind}-v3.webp`;
    if (destinations.has(asset)) throw new Error('Duplicate asset: ' + asset);
    destinations.add(asset);
    const set = artwork[cardId] ??= { banner: '', deckCover: '', stickers: [] };
    if (kind === 'banner') set.banner = asset;
    else if (kind === 'deck-cover') set.deckCover = asset;
    else {
      const variant = kind.replace('sticker-', '');
      const label = { portrait: 'Portrait', action: 'Action', reaction: 'Reaction', emblem: 'Emblem', finnam: 'FINNAM!', falcon: 'Falcon' }[variant];
      set.stickers.push({ id: `${cardId}:v3-${variant}`, name: label, image: asset });
    }
    return { ...entry, cardId, kind, asset };
  });
  for (const [cardId, set] of Object.entries(artwork)) {
    if (!set.banner || !set.deckCover || !set.stickers.length) throw new Error('Incomplete collection: ' + cardId);
    const order = ['portrait', 'action', 'reaction', 'emblem', 'finnam', 'falcon'];
    set.stickers.sort((a, b) => order.indexOf(a.id.split(':v3-')[1]) - order.indexOf(b.id.split(':v3-')[1]));
  }
  let cursor = 0;
  await Promise.all(Array.from({ length: 4 }, async () => {
    while (cursor < jobs.length) {
      const entry = jobs[cursor++];
      const output = path.join(root, 'artifacts/squabblemon/public', entry.asset);
      await mkdir(path.dirname(output), { recursive: true });
      const width = entry.kind === 'banner' ? 1600 : entry.kind === 'deck-cover' ? 768 : 512;
      const info = await sharp(entry.source).resize({ width, withoutEnlargement: true })
        .webp({ quality: 88, alphaQuality: 100, effort: 6 }).toFile(output);
      provenance.push({ pack: entry.pack, member: entry.member, sha256: entry.sha256, sourceBytes: entry.bytes, asset: entry.asset, width: info.width, height: info.height, bytes: info.size });
    }
  }));
  const ordered = Object.fromEntries(Object.entries(artwork).sort(([a], [b]) => a.localeCompare(b)));
  const manifest = '// Generated by scripts/import-character-cosmetics.mjs. Do not hand-edit.\n' +
    'export const CHARACTER_STYLE_ARTWORK: Record<string, { banner: string; deckCover: string; stickers: { id: string; name: string; image: string }[] }> = ' + JSON.stringify(ordered, null, 2) + ';\n';
  await writeFile(path.join(root, 'lib/squabblemon-engine/src/characterStyleArtwork.ts'), manifest);
  const sources = await Promise.all(packNames.map(async pack => ({ pack, sha256: createHash('sha256').update(await readFile(path.join(input, pack))).digest('hex') })));
  await mkdir(path.join(root, 'artifacts/squabblemon/reference/cosmetics'), { recursive: true });
  await writeFile(path.join(root, 'artifacts/squabblemon/reference/cosmetics/import-manifest.json'), JSON.stringify({ sources, images: provenance.sort((a, b) => a.asset.localeCompare(b.asset)) }, null, 2) + '\n');
  console.log(JSON.stringify({ characters: Object.keys(artwork).length, images: entries.length, sourceBytes: entries.reduce((n, e) => n + e.bytes, 0), outputBytes: provenance.reduce((n, e) => n + e.bytes, 0) }));
} finally {
  await rm(scratch, { recursive: true, force: true });
}
